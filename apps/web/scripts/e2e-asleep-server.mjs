import { chromium } from "playwright-core";
// Proves the site stays usable while the free API host is asleep: the API is blocked, pages must still render from the
// saved snapshot, and live data must take over when the API comes back. Usage: BASE=http://localhost:4173 CHROME=... node ...
const BASE = process.env.BASE ?? "http://localhost:4173";
const exe = process.env.CHROME ?? "/usr/bin/google-chrome-stable";
const b = await chromium.launch({ executablePath: exe, args: ["--no-sandbox", "--disable-web-security"] });
const page = await (await b.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
const errs = []; page.on("pageerror", (e) => errs.push(e.message));
let asleep = true;
await page.route("**/*onrender.com/**", (route) => (asleep ? route.abort("connectionrefused") : route.continue()));
const log = (m) => console.log(`[${((Date.now() - t0) / 1000).toFixed(1)}s] ${m}`);
const t0 = Date.now();
await page.goto(`${BASE}/#/`);
await page.getByText(/% /).first().waitFor({ timeout: 15000 }).catch(() => {});
log("landing stat tiles: " + (await page.locator(".stat b").allInnerTexts()).join(" | "));
await page.goto(`${BASE}/#/console?lead=bc1q5frsvq&tab=why`);
await page.reload();
await page.locator(".lead").first().waitFor({ timeout: 15000 });
log("leads in list while asleep: " + (await page.locator(".lead").count()));
await page.locator(".contrib").first().waitFor({ timeout: 15000 });
log("why bars while asleep: " + (await page.locator(".contrib").count()));
log("banner: " + (await page.locator(".wake b").innerText()));
await page.getByRole("tab", { name: "Network" }).click();
await page.getByRole("cell", { name: "40.94.238.111" }).waitFor({ timeout: 15000 });
log("network tab ok while asleep");
await page.getByLabel("Search the dataset").fill("AS8075");
await page.getByRole("option").first().waitFor({ timeout: 15000 });
await page.getByRole("option").first().click();
await page.getByRole("heading", { name: /AS number dossier/ }).waitFor({ timeout: 15000 });
log("AS search ok while asleep");
await page.goto(`${BASE}/#/console?lead=bc1q9506uy&tab=path`);
await page.locator(".pathnode").first().waitFor({ timeout: 15000 });
log("path tab ok while asleep: " + (await page.locator(".pathnode").count()) + " nodes");
await page.goto(`${BASE}/#/how-it-works`);
await page.locator(".model-card").first().waitFor({ timeout: 15000 });
log("how-it-works models while asleep: " + (await page.locator(".model-card").count()));
log("server wakes now");
asleep = false;
await page.waitForFunction(() => !document.querySelector(".wake"), null, { timeout: 90000 });
log("banner gone; pill: " + (await page.locator(".pill").innerText()));
await page.waitForTimeout(2500);
log("models after wake: " + (await page.locator(".model-card").count()) + " | page errors: " + errs.length);
await b.close();
